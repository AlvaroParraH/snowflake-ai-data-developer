"""Preview or create a reviewable dbt model and documentation template."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys


IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_$]*\Z")
DOMAIN = re.compile(r"[a-z][a-z0-9_]*\Z")
MODEL_PREFIXES = {
    "staging": re.compile(r"stg_[a-z0-9_]+__[a-z0-9_]+\Z"),
    "intermediate": re.compile(r"int_[a-z0-9_]+__[a-z0-9_]+\Z"),
    "marts": re.compile(r"(?:dim|fct)_[a-z0-9_]+\Z"),
}
LAYER_PATHS = {
    "staging": Path("models/silver/staging"),
    "intermediate": Path("models/silver/intermediate"),
    "marts": Path("models/gold/marts"),
}


def parse_columns(values: list[str]) -> list[tuple[str, str]]:
    columns: list[tuple[str, str]] = []
    seen: set[str] = set()
    for value in values:
        output_name, separator, source_name = value.partition("=")
        if not separator:
            output_name = source_name = value
        if not IDENTIFIER.fullmatch(output_name) or not IDENTIFIER.fullmatch(source_name):
            raise ValueError(
                f"Invalid column mapping {value!r}; use an identifier or output=source."
            )
        if output_name.lower() in seen:
            raise ValueError(f"Duplicate output column: {output_name}")
        seen.add(output_name.lower())
        columns.append((output_name, source_name))
    if not columns:
        raise ValueError("Provide at least one --column; the generator does not assume source columns.")
    return columns


def validate_arguments(args: argparse.Namespace) -> list[tuple[str, str]]:
    if not DOMAIN.fullmatch(args.domain):
        raise ValueError("Domain must be a lowercase identifier using letters, digits, and underscores.")
    if args.layer not in LAYER_PATHS:
        raise ValueError(f"Unsupported model layer: {args.layer}")
    if not MODEL_PREFIXES[args.layer].fullmatch(args.model_name):
        example = {
            "staging": "stg_sales__orders",
            "intermediate": "int_orders__enriched",
            "marts": "dim_customers or fct_sales",
        }[args.layer]
        raise ValueError(f"Model name does not follow {args.layer} naming; example: {example}.")

    is_staging = args.layer == "staging"
    if is_staging:
        if not args.source_name or not args.source_table or args.upstream_model:
            raise ValueError(
                "Staging models require --source-name and --source-table, "
                "and do not accept --upstream-model."
            )
        if not IDENTIFIER.fullmatch(args.source_name) or not IDENTIFIER.fullmatch(args.source_table):
            raise ValueError("Source name and table must be simple SQL identifiers.")
    elif not args.upstream_model or args.source_name or args.source_table:
        raise ValueError(
            "Intermediate and mart models require --upstream-model and do not accept source options."
        )
    elif not IDENTIFIER.fullmatch(args.upstream_model):
        raise ValueError("Upstream model must be a simple dbt model identifier.")

    columns = parse_columns(args.column)
    test_columns = set(args.not_null) | set(args.unique)
    selected_columns = {output.lower() for output, _ in columns}
    for name in test_columns:
        if not IDENTIFIER.fullmatch(name) or name.lower() not in selected_columns:
            raise ValueError(
                f"Test column {name!r} must be a valid output column selected by --column."
            )
    return columns


def _yaml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def render_files(args: argparse.Namespace) -> dict[Path, bytes]:
    columns = validate_arguments(args)
    not_null_columns = {name.lower() for name in args.not_null}
    unique_columns = {name.lower() for name in args.unique}
    directory = LAYER_PATHS[args.layer] / args.domain
    sql_path = directory / f"{args.model_name}.sql"
    yaml_path = directory / f"{args.model_name}.yml"
    relation = (
        f"{{{{ source('{args.source_name}', '{args.source_table}') }}}}"
        if args.layer == "staging"
        else f"{{{{ ref('{args.upstream_model}') }}}}"
    )
    select_columns = ",\n".join(
        f"        {source}" + (f" as {output}" if output != source else "")
        for output, source in columns
    )
    projection = ",\n".join(f"    {output}" for output, _ in columns)
    sql = f"""-- Starter generated by scaffold_dbt_model.py.
-- Confirm source column names, grain, types, and business rules before building.
with upstream as (

    select
{select_columns}
    from {relation}

)

select
{projection}
from upstream
"""

    lines = [
        "version: 2",
        "",
        "models:",
        f"  - name: {args.model_name}",
        f"    description: {_yaml_string(args.description or 'Starter model; confirm grain and business meaning.')}",
        "    columns:",
    ]
    for output, _ in columns:
        lines.extend((
            f"      - name: {output}",
            f"        description: {_yaml_string('TODO: document ' + output + '.')}",
        ))
        tests = []
        if output.lower() in not_null_columns:
            tests.append("not_null")
        if output.lower() in unique_columns:
            tests.append("unique")
        if tests:
            lines.append("        data_tests:")
            lines.extend(f"          - {test}" for test in tests)
    yaml_content = "\n".join(lines) + "\n"
    return {
        sql_path: sql.encode("utf-8"),
        yaml_path: yaml_content.encode("utf-8"),
    }


def plan(target: Path, args: argparse.Namespace) -> tuple[dict[Path, bytes], list[Path]]:
    if target.is_symlink() or not target.is_dir():
        raise ValueError("Target must be an existing, non-symlink dbt project directory.")
    target = target.resolve()
    project_file = target / "dbt_project.yml"
    if project_file.is_symlink() or not project_file.is_file():
        raise ValueError(f"Target must contain a regular dbt_project.yml: {project_file}")

    files = render_files(args)
    directories: list[Path] = []
    seen: set[Path] = set()
    conflicts: list[str] = []
    for relative in files:
        current = target
        for part in relative.parts[:-1]:
            current /= part
            if current.is_symlink():
                raise ValueError(f"Refusing symlink directory: {current}")
            if current.exists() and not current.is_dir():
                raise ValueError(f"Not a directory: {current}")
            if not current.exists() and current not in seen:
                directories.append(current.relative_to(target))
                seen.add(current)
        destination = target / relative
        if destination.is_symlink():
            raise ValueError(f"Refusing symlink file: {destination}")
        if destination.exists():
            conflicts.append(relative.as_posix())
    if conflicts:
        raise FileExistsError(
            "Refusing to overwrite existing model files:\n  " + "\n  ".join(conflicts)
        )
    return files, directories


def create_files(target: Path, files: dict[Path, bytes], directories: list[Path]) -> None:
    created_directories: list[Path] = []
    created_files: list[Path] = []
    try:
        for relative in directories:
            (target / relative).mkdir()
            created_directories.append(relative)
        for relative, content in files.items():
            destination = target / relative
            with destination.open("xb") as stream:
                stream.write(content)
            created_files.append(relative)
    except OSError:
        print(
            f"Scaffolding interrupted after creating {len(created_directories)} "
            f"directories and {len(created_files)} files; inspect the dbt project before retrying.",
            file=sys.stderr,
        )
        raise


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Preview or create a dbt model and matching model documentation.",
    )
    parser.add_argument("--target", type=Path, required=True, help="Existing dbt project root")
    parser.add_argument("--layer", choices=tuple(LAYER_PATHS), required=True)
    parser.add_argument("--domain", required=True, help="Lowercase folder/domain name")
    parser.add_argument("--model-name", required=True, help="Full model name following the selected layer convention")
    parser.add_argument("--source-name", help="Declared dbt source name (staging only)")
    parser.add_argument("--source-table", help="Declared dbt source table (staging only)")
    parser.add_argument("--upstream-model", help="Existing dbt model referenced by intermediate/mart models")
    parser.add_argument(
        "--column", action="append", default=[], metavar="NAME|OUTPUT=SOURCE",
        help="Selected output column; repeat for each column. Names must be simple SQL identifiers.",
    )
    parser.add_argument("--description", default="", help="Reviewed model purpose/grain description")
    parser.add_argument("--not-null", action="append", default=[], metavar="COLUMN")
    parser.add_argument("--unique", action="append", default=[], metavar="COLUMN")
    parser.add_argument("--dry-run", action="store_true", help="Print complete file preview without writing")
    parser.add_argument("--yes", action="store_true", help="Approve the displayed plan")
    args = parser.parse_args(argv)

    try:
        files, directories = plan(args.target.expanduser(), args)
        target = args.target.expanduser().resolve()
        print(f"dbt project: {target}")
        for relative in directories:
            print(f"MKDIR {relative}")
        for relative, content in files.items():
            print(f"CREATE {relative}")
            if args.dry_run:
                print(content.decode("utf-8"))
        if args.dry_run:
            print("Dry run complete. No dbt project files written.")
            return 0
        if not args.yes:
            if not sys.stdin.isatty():
                raise ValueError("Non-interactive generation requires --yes; preview with --dry-run.")
            if input("Create these dbt model files? [y/N] ").strip().lower() not in {"y", "yes"}:
                print("Cancelled. No model files written.")
                return 0
        create_files(target, files, directories)
        print(f"Created {len(files)} model files. dbt and Snowflake were not run.")
        return 0
    except (OSError, ValueError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
